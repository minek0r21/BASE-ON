"""
talk 메뉴 — 기록 숫자가 아닌 야구 질문(용어 · 규칙 · 관람 · 입문)에 AI가 일반 설명으로 답한다.
  · 답에는 화면이 「일반 설명 · BASE:ON 기록 아님」 꼬리표를 단다
  · 선수 · 팀 · 시즌 숫자는 쓰지 않는다 (그건 기록 메뉴가 DB로 답한다). 숫자 기록처럼 보이는 답은 버리고 안내로 바꾼다
  · 용어 설명은 사이트 「?」 말풍선과 같은 문장을 먼저 쓴다 (GLOSSARY — frontend lib/constants.ts · SeasonsTab.tsx에서 옮김)
"""
import re

from . import llm

# 사이트 「?」 문장 그대로 (바꾸면 화면 쪽도 같이)
GLOSSARY = {
    "규정타석": "규정타석은 팀 경기 수 × 3.1타석이에요. 그 절반 이상 타석에 선 타자끼리 비교해요.",
    "규정이닝": "규정이닝은 팀 경기 수 × 1이닝이에요. 선발은 그 절반 이상, 구원은 5분의 1 이상 던진 투수끼리 비교해요.",
    "OPS": "출루율 + 장타율. 얼마나 자주 나가고 얼마나 멀리 치는지를 한 숫자로 본 타격 점수예요. 1.000을 넘으면 리그 최상위권이에요.",
    "WHIP": "이닝마다 내보낸 주자 수예요((볼넷 + 안타) ÷ 이닝). 낮을수록 좋아요.",
    "타수": "타석에서 볼넷 · 몸에 맞는 공 · 희생타를 뺀 수예요. 타율은 안타 ÷ 타수로 계산해요.",
    "출루율": "타석에서 살아 나간 비율",
    "장타율": "타수당 루타 수 — 장타를 많이 칠수록 높다",
    "이닝": "이닝은 「회」예요. 아웃 3개가 1이닝이라, ⅓은 아웃 1개 · ⅔는 아웃 2개를 더 잡았다는 뜻이에요.",
    "피안타율": "맞은 안타 비율 · 낮을수록 좋아요",
    "사구": "몸에 맞는 공",
    "순수 장타력": "장타율 − 타율. 2루타 · 3루타 · 홈런이 많을수록 커요.",
    "삼진 비율": "타석 중 삼진 비율",
    "볼넷 비율": "타석 중 볼넷 비율",
}


def system() -> str:
    terms = "\n".join(f"- {k}: {v}" for k, v in GLOSSARY.items())
    return f"""너는 KBO 야구 기록 서비스 BASE:ON의 입문 팬 도우미다. 야구 용어 · 규칙 · 관람 · 입문 질문에 쉽게 설명한다.

[규칙]
- 3~4문장, 해요체, 마크다운 · 이모지 없이. 줄임말은 풀어 쓴다 (K → 삼진, 사구 → 몸에 맞는 공).
- 아래 [용어]에 있는 말은 그 문장을 바탕으로 설명한다 (사이트 설명과 같아야 한다).
- 특정 선수 · 팀 · 시즌의 기록 숫자(홈런 수, 타율, 승패, 순위)는 절대 쓰지 않는다. 그런 질문이면 \"선수 이름과 시즌을 넣어 기록으로 물어봐 주세요\"라고만 한다.
- 해마다 바뀌는 KBO 규정(자동 볼 판정, 피치클록, 연장전, 외국인 선수 수 등)은 단정하지 말고 \"KBO 공식 규정에서 확인해 주세요\"를 덧붙인다.
- 최신 소식 · 트레이드 · 지금 로스터 · 일정은 모른다고 말한다.
- 야구와 관계없는 질문이면 \"야구 질문만 답할 수 있어요\"라고 짧게 답한다.

[용어]
{terms}"""


# 기록 숫자처럼 보이는 것: .321 같은 비율, 「36홈런 · 12승 · 3위 · 89타점」. 규칙 숫자(「볼 4개 · 3아웃 · 9이닝 · 7전 4승제」)는 통과
RECORD_LIKE = re.compile(r"(?<![\d.])\.\d{3}(?!\d)|\d+\s*(?:홈런|승(?!제)|패|타점|위|세이브|홀드|도루)")


def answer(message: str) -> tuple[str, bool]:
    """(답, 안전한가). 기록 숫자처럼 보이면 버리고 안내 문장"""
    text = llm.complete(system(), message).strip()
    if RECORD_LIKE.search(text):
        return "기록 숫자는 선수 이름과 시즌을 넣어 물어봐 주세요. 예: 김도영 2024 홈런", False
    return text, True
